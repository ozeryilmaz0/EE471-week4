// All arithmetic is done by the Flask backend. Resolves with the result,
// or rejects with the "error" message sent by the server.
async function calculate(x, operation, y) {
    let response;
    try {
        response = await fetch("/api/calculate", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ x: x, y: y, operation: operation }),
        });
    } catch (err) {
        throw new Error("Server unavailable");
    }

    let data = null;
    try {
        data = await response.json();
    } catch (err) {
        // Not a JSON reply (e.g. an HTML error page); handled below
    }

    if (!response.ok || data === null || typeof data !== "object") {
        throw new Error((data && data.error) || "Server error (" + response.status + ")");
    }
    return data.result;
}

// Sounds are played one after another so they never overlap. Each queue item
// is a promise of an audio URL (null = skip), so speech that is still being
// generated by the server keeps its place in the queue.
const audioQueue = [];
let audioPlaying = false;

function enqueueSound(source) {
    audioQueue.push(Promise.resolve(source));
    if (!audioPlaying) {
        playNextSound();
    }
}

async function playNextSound() {
    if (audioQueue.length === 0) {
        audioPlaying = false;
        return;
    }
    audioPlaying = true;

    const url = await audioQueue.shift();
    if (url === null) {
        playNextSound();
        return;
    }

    const audio = new Audio(url);
    let finished = false;
    const done = () => {
        // "error" and a rejected play() can both fire for the same sound
        if (finished) return;
        finished = true;
        if (url.startsWith("blob:")) {
            URL.revokeObjectURL(url);
        }
        playNextSound();
    };
    audio.addEventListener("ended", done);
    audio.addEventListener("error", done);
    audio.play().catch(done);
}

// Pre-generated word in static/sounds/
function playWord(word) {
    enqueueSound("/sounds/" + word + ".wav");
}

// Asks the server to synthesize any text; resolves with a playable URL, or null on failure
async function fetchSpeech(text) {
    try {
        const response = await fetch("/api/speak", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({ text: text }),
        });
        if (!response.ok) {
            throw new Error("Server error (" + response.status + ")");
        }
        return URL.createObjectURL(await response.blob());
    } catch (err) {
        console.warn("Speech unavailable:", err.message);
        return null;
    }
}

function speak(text) {
    enqueueSound(fetchSpeech(text));
}

const DIGIT_WORDS = {
    "0": "zero",
    "1": "one",
    "2": "two",
    "3": "three",
    "4": "four",
    "5": "five",
    "6": "six",
    "7": "seven",
    "8": "eight",
    "9": "nine",
    ".": "point",
};

const OPERATION_WORDS = {
    divide: "over",
    multiply: "times",
    add: "plus",
    subtract: "minus",
};

const MAX_DIGITS = 16;

const display = document.getElementById("display");

let current = "0";        // number currently being typed / shown
let firstNumber = null;   // stored left-hand operand
let operation = null;     // stored operation name
let startNew = true;      // next digit starts a fresh number
let waiting = false;      // a request to the server is in progress
let hasError = false;     // an error message is shown instead of a number

function updateDisplay() {
    hasError = false;
    display.classList.remove("error");
    display.textContent = current;
}

function clearAll() {
    current = "0";
    firstNumber = null;
    operation = null;
    startNew = true;
    updateDisplay();
}

function showError(message) {
    clearAll();   // next digit starts a fresh number
    hasError = true;
    display.classList.add("error");
    display.textContent = message;
}

// quiet = true skips the key sound (used for voice commands)
function inputDigit(digit, quiet = false) {
    if (waiting) return;
    if (startNew) {
        current = digit === "." ? "0." : digit;
        startNew = false;
    } else if (digit === ".") {
        if (current.includes(".")) return;
        current += ".";
    } else if (current === "0") {
        current = digit;
    } else {
        if (current.replace(/[-.]/g, "").length >= MAX_DIGITS) return;
        current += digit;
    }
    // Only reached when the key was accepted, so ignored keys stay silent
    if (!quiet) {
        playWord(DIGIT_WORDS[digit]);
    }
    updateDisplay();
}

// Asks the server for firstNumber <operation> current; returns false on an error.
async function evaluatePending() {
    waiting = true;
    try {
        const result = await calculate(firstNumber, operation, parseFloat(current));
        current = String(result);
        updateDisplay();
        return true;
    } catch (err) {
        showError(err.message);
        speak("error");
        return false;
    } finally {
        waiting = false;
    }
}

async function chooseOperation(op, quiet = false) {
    // After an error there is no number to operate on; wait for a digit
    if (waiting || hasError) return;
    if (!quiet) {
        playWord(OPERATION_WORDS[op]);
    }
    // A second operator after typing another number chains the calculation (2 + 3 + → 5)
    if (operation !== null && !startNew) {
        if (!(await evaluatePending())) return;
    }
    firstNumber = parseFloat(current);
    operation = op;
    startNew = true;
}

async function equals() {
    if (waiting || operation === null) return;
    if (!(await evaluatePending())) return;
    // Azure reads digits as words, e.g. "is 8" is spoken as "is eight"
    speak("is " + current);
    firstNumber = null;
    operation = null;
    startNew = true;
}

function backspace() {
    if (waiting || startNew) return;   // don't edit a result
    current = current.slice(0, -1);
    if (current === "" || current === "-") {
        current = "0";
    }
    updateDisplay();
}

// Mouse input
document.querySelectorAll(".digit").forEach((button) => {
    button.addEventListener("click", () => inputDigit(button.dataset.value));
});

document.querySelectorAll(".operator").forEach((button) => {
    button.addEventListener("click", () => chooseOperation(button.dataset.op));
});

document.getElementById("equals").addEventListener("click", equals);

display.addEventListener("click", clearAll);

// Keyboard input
const KEY_OPERATIONS = {
    "+": "add",
    "-": "subtract",
    "*": "multiply",
    "/": "divide",
};

document.addEventListener("keydown", (event) => {
    // Leave browser shortcuts such as Ctrl + / Ctrl - (zoom) alone
    if (event.ctrlKey || event.metaKey || event.altKey) return;

    const key = event.key;

    if (/^[0-9.]$/.test(key)) {
        inputDigit(key);
    } else if (key in KEY_OPERATIONS) {
        chooseOperation(KEY_OPERATIONS[key]);
    } else if (key === "Enter" || key === "=") {
        equals();
    } else if (key === "Backspace") {
        backspace();
    } else if (key === "Escape") {
        clearAll();
    } else {
        return;
    }

    // Stops "/" opening quick-find and Enter re-clicking a focused button
    event.preventDefault();
});

// Voice commands: record with the microphone button, let the server turn the
// speech into key symbols, then press those keys one by one.
const micButton = document.getElementById("mic");
const voiceStatus = document.getElementById("voice-status");

const VOICE_KEY_DELAY_MS = 400;

// Key symbols returned by /api/voice-command (same as on the buttons)
const TOKEN_OPERATIONS = {
    "÷": "divide",
    "×": "multiply",
    "−": "subtract",
    "+": "add",
};

let mediaRecorder = null;   // active recorder while recording
let voiceBusy = false;      // waiting for the microphone, the server or the key presses

function setVoiceStatus(message, isError = false) {
    voiceStatus.textContent = message;
    voiceStatus.classList.toggle("error", isError);
}

function sleep(ms) {
    return new Promise((resolve) => setTimeout(resolve, ms));
}

// Briefly darken the button for a token so the key press is visible
function flashKey(token) {
    let button;
    if (token === "=") {
        button = document.getElementById("equals");
    } else if (token in TOKEN_OPERATIONS) {
        button = document.querySelector('.operator[data-op="' + TOKEN_OPERATIONS[token] + '"]');
    } else {
        button = document.querySelector('.digit[data-value="' + token + '"]');
    }
    if (!button) return;
    button.classList.add("pressed");
    setTimeout(() => button.classList.remove("pressed"), 150);
}

// Press one key through the same functions the buttons use, without key sounds
async function pressToken(token) {
    flashKey(token);
    if (token === "=") {
        await equals();   // still speaks "is <result>"
    } else if (token in TOKEN_OPERATIONS) {
        await chooseOperation(TOKEN_OPERATIONS[token], true);
    } else if (/^[0-9.]$/.test(token)) {
        inputDigit(token, true);
    }
}

async function applyTokens(tokens) {
    for (let i = 0; i < tokens.length; i++) {
        if (i > 0) {
            await sleep(VOICE_KEY_DELAY_MS);
        }
        await pressToken(tokens[i]);
    }
}

async function sendVoiceCommand(blob) {
    voiceBusy = true;
    micButton.disabled = true;
    setVoiceStatus("Processing…");

    try {
        // The server converts any format with ffmpeg; the extension is only a hint
        const extension = blob.type.includes("ogg") ? "ogg" : blob.type.includes("mp4") ? "mp4" : "webm";
        const formData = new FormData();
        formData.append("audio", blob, "command." + extension);

        let response;
        try {
            response = await fetch("/api/voice-command", { method: "POST", body: formData });
        } catch (err) {
            throw new Error("Server unavailable");
        }

        let data = null;
        try {
            data = await response.json();
        } catch (err) {
            // Not a JSON reply (e.g. an HTML error page); handled below
        }

        if (!response.ok || data === null || typeof data !== "object") {
            throw new Error((data && data.error) || "Server error (" + response.status + ")");
        }

        setVoiceStatus("Heard: " + data.heard);
        await applyTokens(data.tokens);
    } catch (err) {
        setVoiceStatus(err.message, true);
    } finally {
        voiceBusy = false;
        micButton.disabled = false;
    }
}

async function startRecording() {
    if (!navigator.mediaDevices || !window.MediaRecorder) {
        setVoiceStatus("Recording is not supported in this browser", true);
        return;
    }

    // Ignore clicks while the browser is asking for microphone permission
    voiceBusy = true;
    let stream;
    try {
        stream = await navigator.mediaDevices.getUserMedia({ audio: true });
    } catch (err) {
        setVoiceStatus("Microphone access was denied", true);
        return;
    } finally {
        voiceBusy = false;
    }

    const chunks = [];
    const recorder = new MediaRecorder(stream);
    recorder.addEventListener("dataavailable", (event) => {
        if (event.data.size > 0) {
            chunks.push(event.data);
        }
    });
    recorder.addEventListener("stop", () => {
        stream.getTracks().forEach((track) => track.stop());   // release the microphone
        sendVoiceCommand(new Blob(chunks, { type: recorder.mimeType || "audio/webm" }));
    });

    recorder.start();
    mediaRecorder = recorder;
    micButton.classList.add("recording");
    micButton.setAttribute("aria-label", "Stop and send voice command");
    setVoiceStatus("Listening… click the microphone again to send");
}

function stopRecording() {
    micButton.classList.remove("recording");
    micButton.setAttribute("aria-label", "Start voice command");
    mediaRecorder.stop();   // the "stop" handler sends the recording
    mediaRecorder = null;
}

micButton.addEventListener("click", () => {
    if (voiceBusy) return;
    if (mediaRecorder) {
        stopRecording();
    } else {
        startRecording();
    }
});
